#!/usr/bin/env python3
"""Pure Etas admission, settlement/prefix and atomic CLI argument contracts."""
from copy import deepcopy
import json
import os
from pathlib import Path
import shutil
import subprocess
import tempfile

from normal_graph_identity import digest, verify_cli
from session_state_probe import snapshot, request, render, record, event, reference

ROOT = Path(__file__).resolve().parent.parent


def main():
    cli = verify_cli()
    project = Path(tempfile.mkdtemp(prefix='continue-state-', dir=os.environ['NOMO_TEST_EVIDENCE']))
    print('EVIDENCE ' + str(project), flush=True)
    target = project / 'src/nomo'
    target.mkdir(parents=True)
    names = ['conversation.es', 'text.es', 'session_state.es', 'stub_snapshot.es', 'store_record.es',
             'bundle_codec.es', 'continuation_args.es', 'continuation_state.es', 'session_cli_args.es']
    before = {name: digest(ROOT / 'src/nomo' / name) for name in names}
    for name in names:
        shutil.copyfile(ROOT / 'src/nomo' / name, target / name)
    app = project / 'src/app/main.es'
    app.parent.mkdir()
    base = snapshot()
    base[1]['generation'] = 0
    for key in ['original_caps', 'current_caps']:
        base[1][key][1]['turn_steps'] = 3
    cases = []

    def plan_case(label, saved, req, generation, text, reserved=None):
        test = 'Err(_) => {}, Ok(_) => { abort("unexpected admission"); }' if reserved is None else (
            'Err(_) => { abort("valid admission refused"); }, Ok(value) => { '
            f'if value.reserved != {reserved} || value.prior.history.spent != {saved[1]["history"][1]["spent"]} '
            '{ abort("reservation or cumulative consumption changed"); } }')
        cases.append((label, f'let saved = {render(saved)}; let requested = {render(req)}; '
                     f'match plan(saved, requested, {generation}, {json.dumps(text)}) {{ {test} }};'))

    plan_case('three_step_absolute_reservation', base, request(base), 0, 'recall', 6)
    for steps, budget, expected in [(16, 16, 6), (1, 16, 4), (2, 5, 5), (3, 4, 4), (3, 3, None)]:
        req = request(base)
        req[1]['caps'][1].update(turn_steps=steps, steps=budget)
        plan_case(f'constrained_{steps}_{budget}', base, req, 0, 'recall', expected)
    for label, generation, text in [('stale_generation', 1, 'recall'), ('invalid_generation', -1, 'recall'),
                                    ('invalid_input', 0, ''), ('command_input', 0, '/help')]:
        plan_case(label, base, request(base), generation, text)
    for label, fields in [('stopped', {'lifecycle': 'stopped'}), ('recovery', {'lifecycle': 'recovery-required'}),
                          ('wrong_generation', {'generation': 2}), ('unsupported_mode', {'mode': 'other'})]:
        changed = deepcopy(base)
        changed[1].update(fields)
        if label == 'stopped':
            changed[1]['history'][1]['stopped'] = True
        plan_case(label, changed, request(base), 0, 'recall')
    for field in ['session_id', 'binding', 'mode']:
        req = request(base)
        req[1][field] = 'wrong'
        plan_case('requested_' + field, base, req, 0, 'recall')
    for status in ['pending', 'unknown']:
        changed = deepcopy(base)
        changed[1]['history'][1]['events'].pop()
        changed[1]['history'][1]['characters'] = 9
        changed[1]['references'].pop()
        changed[1]['operations'][0][1]['status'] = status
        plan_case(status, changed, request(base), 0, 'recall')
    for size, content in [(28, ''), (1, 'x' * 7100)]:
        changed = deepcopy(base)
        changed[1]['history'][1].update(events=[event(text=content)] * size, characters=size * len(content))
        changed[1]['operations'] = []
        changed[1]['references'] = [reference()] * size
        plan_case('capacity_' + str(size), changed, request(base), 0, 'x' * 1024 if content else 'recall')
    req = request(base)
    req[1]['caps'][1]['steps'] = 2147483647
    plan_case('overflow_caps_refused_before_arithmetic', base, req, 0, 'recall')

    # The prior operation ID is deliberately not generated by the stub mapper.
    completed = deepcopy(base[1]['history'])
    completed[1]['events'] += [event(text='tool:echo:new'), event('model', 'request', 'echo', 'new'),
                               event('tool', 'complete', 'echo', 'new'), event('assistant', 'final', '', 'stub received: new')]
    completed[1]['characters'] = sum(len(e[1]['name']) + len(e[1]['text']) for e in completed[1]['events'])
    completed[1]['spent'] = 6
    mapping = f'''let saved = {render(base)};
    let requested = {render(request(base))};
    let admitted = match plan(saved, requested, 0, "tool:echo:new") {{ Ok(v) => v, Err(_) => {{ abort("plan refused"); }} }};
    let row = continuing(admitted, "save2");
    if row.phase != "continuing" || row.save_id != "save2" || row.snapshot.generation != 0 ||
        row.snapshot.history.spent != 6 || !row.snapshot.history.stopped || row.snapshot.lifecycle != "recovery-required" ||
        row.snapshot.operations != saved.operations || row.snapshot.original_caps != saved.original_caps {{ abort("admission association changed"); }}
    let state = {render(completed)};
    let outcome = match successor(state, admitted.prior, admitted.reserved, 0) {{ Ok(v) => v, Err(_) => {{ abort("settlement refused"); }} }};
    if outcome.generation != 1 || outcome.original_caps != saved.original_caps || outcome.ledger != saved.ledger ||
        outcome.operations[0] != saved.operations[0] || outcome.references[1] != saved.references[1] ||
        outcome.references[2] != saved.references[2] || outcome.history.events[0] != saved.history.events[0] ||
        outcome.operations[1].id != "stub-successor-request-4" {{ abort("prefix identities or limits changed"); }}
    '''
    cases.append(('admission_descriptor_and_custom_prefix_settlement', mapping))
    for label, changes in [('over_reservation', {'spent': 7}), ('decreased_spending', {'spent': 2}),
                           ('missing_prefix', {'events': [], 'characters': 0}),
                           ('changed_prefix', {'events': [event(text='changed'), *completed[1]['events'][1:]]})]:
        altered = deepcopy(completed)
        altered[1].update(changes)
        cases.append((label, f'let saved = {render(base)}; let requested = {render(request(base))}; let state = {render(altered)}; '
                     'let admitted = match plan(saved, requested, 0, "recall") '
                     '{ Ok(v) => v, Err(_) => { abort("plan refused"); } }; '
                     'match successor(state, admitted.prior, admitted.reserved, 0) '
                     '{ Err(_) => {}, Ok(_) => { abort("invalid settlement accepted"); } };'))
    valid = ['continue', '--session', 's', '--save', 'a', '--generation', '0', '--next-save', 'b', '--binding', 'bound', '--input', 'recall']
    parsing = [(valid, True), (valid + ['--steps', '2', '--budget', '5'], True),
               ([*valid[:-1], '--generation'], True), ([], False), (['continue'], False),
               (valid + ['--generation', '0'], False), (valid + ['--next-save', 'c'], False),
               (valid + ['--wat', 'x'], False), (valid + ['--input', 'x'], False), (valid + ['--budget', '17'], False),
               (valid[:-4] + ['--input', 'recall'], False), (valid + ['--budget'], False)]
    same = list(valid)
    same[same.index('--next-save') + 1] = 'a'
    parsing.append((same, False))
    for index, (arguments, expected) in enumerate(parsing):
        test = 'Ok(_) => {}, Err(_) => { abort("valid arguments refused"); }' if expected else 'Err(_) => {}, Ok(_) => { abort("invalid arguments accepted"); }'
        cases.append(('atomic_args_' + str(index), f'match parse_continue({render(arguments)}) {{ {test} }};'))
    source = '''module app.main;
import std.io.println;
import nomo.conversation.{State, Event};
import nomo.session_state.{Snapshot, Request, Caps, Ledger, Operation, Reference};
import nomo.continuation_state.{plan, continuing};
import nomo.stub_snapshot.successor;
import nomo.continuation_args.parse_continue;
'''
    for index, (label, body) in enumerate(cases):
        source += f'flow case_{index}() -> i32 {{ {body} return 0; }}\n'
    source += 'public flow contracts() -> i32 {\n'
    for index in range(len(cases)):
        source += f'let result_{index} = case_{index}();\n'
    source += 'return 0; }\npublic flow main(args: Array<string>) -> i32 { let code = contracts(); println("PASS pure continuation contracts"); return code; }\n'
    app.write_text(source)
    (project / 'etas.toml').write_text('''[package]
name = "continue-state-fixture"
version = "0.0.0"
edition = "2026"
[source]
root = "src"
[runtime]
default_profile = "fixture"
[runtime.profiles.fixture]
boundary_policy = "pure-continuation-probe"
[runtime.profiles.fixture.policy]
mode = "local-static"
rules = ["console=allow"]
[runtime.profiles.fixture.approval]
mode = "deny"
[[bin]]
name = "probe"
module = "app.main"
flow = "main"
''')
    shutil.copyfile(__file__, project / 'driver.py')
    result = {'cases': [label for label, _ in cases], 'commands': [], 'sources':
              {str(p.relative_to(project)): digest(p) for p in project.rglob('*') if p.is_file()}}
    for command in [[str(cli), 'check', '--all', str(project)], [str(cli), 'effects', str(project), '--flow', 'contracts'],
                    [str(cli), 'run', str(project), '--allow-effects']]:
        process = subprocess.run(command, capture_output=True, text=True, timeout=120)
        item = {'command': command, 'exit': process.returncode, 'stdout': process.stdout, 'stderr': process.stderr}
        result['commands'].append(item)
        (project / 'results.json').write_text(json.dumps(result, indent=2))
        assert process.returncode == 0, (command, process.returncode, process.stderr[:6000], str(project / 'results.json'))
        if 'effects' in command:
            assert 'requested actions: []' in process.stdout, item
        if 'run' in command:
            assert process.stdout == 'PASS pure continuation contracts\n', item
    assert {name: digest(ROOT / 'src/nomo' / name) for name in before} == before
    print('PASS ' + str(len(cases)) + ' pure continuation contracts; no Host actions', flush=True)


if __name__ == '__main__':
    main()
